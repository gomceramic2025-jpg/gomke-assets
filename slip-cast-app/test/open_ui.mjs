import * as THREE from 'three';
import { STLExporter } from 'three/examples/jsm/exporters/STLExporter.js';
import { writeFileSync } from 'node:fs';
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const d = process.argv[2], scale = +process.argv[3] || 1, solid = process.argv[4] !== '0';
const shell = new THREE.SphereGeometry(40, 96, 64, 0, Math.PI * 2, 0, Math.PI * 0.62); shell.scale(scale, scale, scale);
const mesh = new THREE.Mesh(shell, new THREE.MeshBasicMaterial());
const dv = new STLExporter().parse(mesh, { binary: true }); writeFileSync(d + '/bowl.stl', Buffer.from(dv.buffer, dv.byteOffset, dv.byteLength));
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=swiftshader','--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } }); const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('file://' + process.cwd() + '/artifact.html');
const settle = () => p.waitForFunction(() => document.getElementById('busy').hidden && /Xong|lỗi/.test(document.getElementById('shStatus').textContent), null, { timeout: 200000 });
await p.waitForTimeout(600); await settle();
if (!solid) await p.uncheck('#autoSolid');
await p.setInputFiles('#file', d + '/bowl.stl');
await p.waitForTimeout(1500); await settle();
console.log('toast:', (await p.textContent('#toast')).slice(0, 300));
console.log((await p.innerText('#phoiInfo')).replace(/\n/g, ' | ').slice(0, 400));
await p.waitForTimeout(800); await p.screenshot({ path: d + '/26_open_' + scale + (solid ? '' : '_ns') + '.png' });
console.log('errors', errs); await b.close();
